"""Getters for help dialog."""

from dependency_injector.wiring import Provide, inject

from app.internal import Container
from app.internal.usecases.organization_service import OrganizationService

# Base navigation data for all steps
BASE_NAVIGATION = {
    "show_prev_button": False,
    "show_next_button": True,
    "is_final_step": False
}


@inject
async def get_help_main_data(
    dialog_manager,
    organization_service: OrganizationService = Provide[Container.organization_service],
    **kwargs
):
    """Get data for main help window."""
    # Check if user has organization
    user_data = dialog_manager.middleware_data.get("user_data", {})
    telegram_id = user_data.get("telegram_id")
    has_organization = False
    
    if telegram_id:
        organization = await organization_service.get_by_user_telegram_id(telegram_id)
        has_organization = organization is not None
    
    return {
        "title": "📚 <b>Добро пожаловать в Restos!</b>",
        "description": "Давайте начнем с интерактивного обучения, чтобы вы могли быстро освоить все возможности системы.",
        "has_organization": has_organization,
    }


